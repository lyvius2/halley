-- 목적 : 운영 DB가 어느 시점에 멈춰 있든 지금 코드가 기대하는 상태로 맞춘다.
--        `relation "system_config" does not exist` 처럼 테이블·컬럼이 없어
--        기동하지 못할 때 쓴다.
--
-- 성질 : 전부 IF NOT EXISTS 다. 몇 번을 돌려도 같은 결과이고, 이미 있는
--        테이블·컬럼·인덱스는 건드리지 않는다. 데이터를 지우지 않는다.
--
-- 출처 : src/main/resources/schema.sql (앱이 실제로 쓰는 스키마)에서 생성.
--        H2 표기를 PostgreSQL로 치환했다 — VARCHAR(1000000) -> TEXT, JSON -> JSONB.
--
-- 사용 : psql "$DATABASE_URL" -f docs/DDL-repair.sql
--
-- 주의 : ADD COLUMN 에는 NOT NULL 을 붙이지 않는다. 이미 행이 들어 있는 테이블에
--        기본값 없는 NOT NULL 컬럼을 더하면 실패하기 때문이다.
-- =============================================================================

