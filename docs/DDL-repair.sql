CREATE TABLE IF NOT EXISTS property_score (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id     BIGINT       NOT NULL,
    criterion_code  VARCHAR(50)  NOT NULL,
    auto_score      DECIMAL(6, 2),
