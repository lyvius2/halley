-- ===========================================================================
-- 가격 전망 재시작 — 429·400 시절에 굳은 값을 걷어낸다
--
-- 언제 쓰나: 초당 제한(I140)과 temperature 400(I144)을 고친 판을 배포한 뒤 한 번.
-- 위에서부터 순서대로 돌린다. 먼저 SELECT 로 몇 건인지 보고 지운다.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 실패가 '거래 0건'으로 굳은 달 (설계 I140)  ★ 이것이 핵심이다
--
--    429 를 맞으면 어댑터가 빈 목록을 돌려줬고, 수집기는 그것을 "그 달은 거래가
--    없었다"로 저장했다. 과거 달은 다시 받지 않으므로(I128) 그 구멍 위에서
--    중앙값이 계산된다 — 지우지 않으면 전망이 계속 헛것을 본다.
--
--    진짜 0건인 달과 구분할 방법이 없다. 그래서 0건을 전부 지운다 —
--    진짜 0건이었으면 다음 수집에서 한 번 더 받고 같은 값으로 다시 굳는다.
-- ---------------------------------------------------------------------------
SELECT deal_type, count(*) AS 지울행수
  FROM monthly_trade_cache
 WHERE trade_count = 0
 GROUP BY deal_type;

DELETE FROM monthly_trade_cache WHERE trade_count = 0;

-- ---------------------------------------------------------------------------
-- 2. LLM 이 400 을 맞고 남긴 전망 (설계 I144)
--
--    temperature 가 거절당하는 동안 LLM 답이 없어 전부 UNCERTAIN 으로 저장됐다.
--    지워야 하는 이유는 둘이다.
--      · UNCERTAIN 은 화살표를 띄우지 않는다 → 모달을 열 길이 없다
--      · stored=true 라 매매가를 눌러도 트리거되지 않는다 (설계 I142)
--    즉 지우지 않으면 화면에서 다시 시킬 방법이 없다.
--
--    확신을 갖고 낸 UP/DOWN/FLAT 은 남겨 둔다 — 그건 정상적으로 나온 답이다.
-- ---------------------------------------------------------------------------
SELECT direction, count(*) FROM price_forecast GROUP BY direction;

DELETE FROM price_forecast WHERE direction = 'UNCERTAIN';

-- ---------------------------------------------------------------------------
-- 3. 같은 기간의 이력 (설계 I138)
--
--    사후 검증(구현 10)의 재료인데, 이 행들은 '모델이 판단한 결과'가 아니라
--    '호출이 실패한 결과'다. 남겨 두면 적중률을 계산할 때 섞여 든다.
--    model 이 비어 있는 것이 LLM 을 못 부른 흔적이다.
-- ---------------------------------------------------------------------------
DELETE FROM price_forecast_history
 WHERE direction = 'UNCERTAIN' AND model IS NULL;

