);

-- ---------------------------------------------------------------------------
-- 4. property_agent — 매물:중개인 N:M
-- ---------------------------------------------------------------------------
CREATE TABLE property_agent (
    property_id BIGINT  NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    agent_id    BIGINT  NOT NULL REFERENCES agent (id)    ON DELETE CASCADE,
    is_primary  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (property_id, agent_id)
);
CREATE INDEX ix_property_agent_agent ON property_agent (agent_id);

-- ---------------------------------------------------------------------------
-- 5. property_image — 매물 이미지 (도면/실사)
-- ---------------------------------------------------------------------------
CREATE TABLE property_image (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id  BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    image_type   VARCHAR(20) NOT NULL,                                   -- FLOOR_PLAN | PHOTO
    storage_path VARCHAR(500) NOT NULL,
    sort_order   INTEGER     NOT NULL DEFAULT 0
);
CREATE INDEX ix_property_image_property ON property_image (property_id, sort_order);

-- ---------------------------------------------------------------------------
-- 6. criterion — 평가 항목
-- ---------------------------------------------------------------------------
CREATE TABLE criterion (
    code         VARCHAR(50) PRIMARY KEY,                                -- COMFORT|PRICE|MOVE_IN|COMMUTE|AGE|FLOOR|STATION|EDUCATION|AMENITY|PARKING|GREEN|HOUSEHOLDS
    name         VARCHAR(100) NOT NULL,
    scoring_type VARCHAR(20)  NOT NULL,                                  -- AUTO | MANUAL | HYBRID
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------------
-- 7. criterion_weight — 평가 항목 가중치(우선순위)
-- ---------------------------------------------------------------------------
CREATE TABLE criterion_weight (
    criterion_code VARCHAR(50) PRIMARY KEY REFERENCES criterion (code),
    priority_rank  INTEGER     NOT NULL,                                 -- 1 = 최우선
    weight         NUMERIC(6, 2) NOT NULL,                               -- 가중치 배수
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_criterion_weight_rank ON criterion_weight (priority_rank);

-- ---------------------------------------------------------------------------
-- 8. property_score — 매물별 항목 점수
-- ---------------------------------------------------------------------------
CREATE TABLE property_score (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id    BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    criterion_code VARCHAR(50) NOT NULL REFERENCES criterion (code),
    auto_score     NUMERIC(6, 2),                                        -- 0~100
    manual_score   NUMERIC(6, 2),
    effective_score NUMERIC(6, 2),
    score_source   VARCHAR(20),                                          -- AUTO | MANUAL | FALLBACK
    fallback_reason VARCHAR(255),                                         -- 미산출 사유 (설계 I47)
    explanation    VARCHAR(500),                                          -- 자동 채점 산출 근거 (설계 I50)
    computed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_property_score UNIQUE (property_id, criterion_code)
);
CREATE INDEX ix_property_score_criterion ON property_score (criterion_code);

-- ---------------------------------------------------------------------------
-- 9. user_criterion_score — 사용자별 수동 점수 (COMFORT 등)
-- ---------------------------------------------------------------------------
CREATE TABLE user_criterion_score (
    property_id    BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    user_id        BIGINT      NOT NULL REFERENCES users (id)    ON DELETE CASCADE,
    criterion_code VARCHAR(50) NOT NULL REFERENCES criterion (code),
    score          INTEGER     NOT NULL,                                 -- 1~5 또는 0~100
    PRIMARY KEY (property_id, user_id, criterion_code)
);
CREATE INDEX ix_user_criterion_score_user ON user_criterion_score (user_id);

-- ---------------------------------------------------------------------------
-- 10. commute_result — 사용자별 직장 통근 결과
-- ---------------------------------------------------------------------------
CREATE TABLE commute_result (
    property_id    BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    user_id        BIGINT      NOT NULL REFERENCES users (id)    ON DELETE CASCADE,
    total_minutes  INTEGER,
    transfer_count INTEGER,
    walk_minutes   INTEGER,
    path_summary   JSONB,
    fetched_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (property_id, user_id)
);

