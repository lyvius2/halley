-- ---------------------------------------------------------------------------
-- 12. property_opinion — 매물 Merit/Demerit 의견
-- ---------------------------------------------------------------------------
CREATE TABLE property_opinion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id  BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    user_id      BIGINT      NOT NULL REFERENCES users (id)    ON DELETE CASCADE,
    opinion_type VARCHAR(20) NOT NULL,                                   -- MERIT | DEMERIT
    content      VARCHAR(1000) NOT NULL,
    sort_order   INTEGER     NOT NULL DEFAULT 0
);
CREATE INDEX ix_property_opinion_property ON property_opinion (property_id, sort_order);

-- ---------------------------------------------------------------------------
-- 13. listing_check_log — 매물 생존 확인 로그
-- ---------------------------------------------------------------------------
CREATE TABLE listing_check_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id BIGINT      NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    checked_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    http_status INTEGER,
    verdict     VARCHAR(20),                                             -- ALIVE | GONE | BLOCKED | ERROR
    evidence    VARCHAR(1000),                                           -- 판정 근거 스니펫
    elapsed_ms  INTEGER,
    notified    BOOLEAN     NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_listing_check_log_property ON listing_check_log (property_id, checked_at);

-- ---------------------------------------------------------------------------
-- 14. system_config — 시스템 설정 (Slack은 yaml로 이관됨)
-- ---------------------------------------------------------------------------
CREATE TABLE system_config (
    config_key   VARCHAR(100) PRIMARY KEY,
    config_value VARCHAR(1000),
    value_type   VARCHAR(20) NOT NULL DEFAULT 'STRING',                  -- STRING | INT | BOOL | SECRET
    category     VARCHAR(20),                                            -- BATCH | SCORING | LOAN
    description  VARCHAR(500),
    masked       BOOLEAN     NOT NULL DEFAULT FALSE,
    updated_by   BIGINT      REFERENCES users (id),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_system_config_category ON system_config (category);

-- ---------------------------------------------------------------------------
-- 15. notification_log — 알림 발송 이력
-- ---------------------------------------------------------------------------
CREATE TABLE notification_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(50) NOT NULL,                                  -- PROPERTY_CREATED|LISTING_SOLD_OUT|BATCH_*...
    property_id   BIGINT      REFERENCES property (id) ON DELETE SET NULL,
    channel       VARCHAR(20),
    status        VARCHAR(20) NOT NULL DEFAULT 'RETRYING',               -- SENT | FAILED | RETRYING
    retry_count   INTEGER     NOT NULL DEFAULT 0,
    error_message VARCHAR(1000),
    payload       JSONB,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at       TIMESTAMPTZ
);
CREATE INDEX ix_notification_log_status ON notification_log (status, created_at);

-- ---------------------------------------------------------------------------
-- 16. reference_transaction — 국토부 실거래가 (참고 표기 전용)
-- ---------------------------------------------------------------------------
CREATE TABLE reference_transaction (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id   BIGINT NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    deal_type     VARCHAR(20),                                           -- TRADE | RENT
    contract_date DATE,
    price         BIGINT,
    floor_no      INTEGER,
    source        VARCHAR(30),                                           -- MINISTRY_TRADE | MINISTRY_RENT
    cached_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_reference_transaction_property ON reference_transaction (property_id, contract_date);

-- ---------------------------------------------------------------------------
-- 17. loan_estimate — 대출 한도 시뮬레이션 결과
-- ---------------------------------------------------------------------------
CREATE TABLE loan_estimate (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id     BIGINT NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    product_type    VARCHAR(20),                                         -- MORTGAGE | JEONSE
    ltv_rate        NUMERIC(6, 4),
    ltv_limit       BIGINT,
    dsr_limit       BIGINT,
    final_limit     BIGINT,
    required_cash   BIGINT,
    acquisition_tax BIGINT,
    assumptions     JSONB,
    computed_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_loan_estimate_property ON loan_estimate (property_id, computed_at);

-- ---------------------------------------------------------------------------
-- 18. property_visit_plan — 임장 플래너 (계획)
-- ---------------------------------------------------------------------------
CREATE TABLE property_visit_plan (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date            DATE,
    created_by            BIGINT NOT NULL REFERENCES users (id),
    start_address         VARCHAR(500),
    start_lat             NUMERIC(12, 8),
    start_lng             NUMERIC(12, 8),
    travel_mode           VARCHAR(20),                                   -- TRANSIT | DRIVING
    window_start          TIME,
    window_end            TIME,
    stay_minutes_default  INTEGER NOT NULL DEFAULT 25,
    status                VARCHAR(20) NOT NULL DEFAULT 'DRAFT',          -- DRAFT | CONFIRMED | COMPLETED
    computed_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_property_visit_plan_created ON property_visit_plan (created_by, visit_date);

-- ---------------------------------------------------------------------------
-- 19. visit_plan_stop — 임장 방문 정거장
-- ---------------------------------------------------------------------------
CREATE TABLE visit_plan_stop (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id                 BIGINT NOT NULL REFERENCES property_visit_plan (id) ON DELETE CASCADE,
    property_id             BIGINT NOT NULL REFERENCES property (id) ON DELETE CASCADE,
    stop_order              INTEGER NOT NULL,
    estimated_arrival       TIME,
    estimated_departure     TIME,
    travel_minutes_from_prev INTEGER,
    travel_mode_segment     VARCHAR(20),
    visited                 BOOLEAN NOT NULL DEFAULT FALSE,
    visited_at              TIMESTAMPTZ,
    CONSTRAINT uq_visit_plan_stop_order UNIQUE (plan_id, stop_order)
);
CREATE INDEX ix_visit_plan_stop_property ON visit_plan_stop (property_id);

-- ---------------------------------------------------------------------------
-- 20. regulation_param — 대출 규제 파라미터 (프로파일별)
-- ---------------------------------------------------------------------------
CREATE TABLE regulation_param (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile     VARCHAR(50)  NOT NULL,                                   -- 규제 파라미터 세트 (예: '2025-10-15')
    param_key   VARCHAR(50)  NOT NULL,                                   -- LTV_RATE|MAX_LOAN_AMOUNT|DSR_LIMIT|STRESS_RATE|ACQUISITION_TAX_BANDS|BROKER_FEE_RATE|FIRST_HOME_PREF_RATE|JEONSE_GUARANTEE_LIMIT
    param_value VARCHAR(1000) NOT NULL,                                  -- 값(숫자·JSON은 문자열로 저장)
    value_type  VARCHAR(20)  NOT NULL DEFAULT 'STRING',                  -- STRING | INT | DECIMAL | JSON
    description VARCHAR(500),
    updated_by  BIGINT       REFERENCES users (id),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_regulation_param UNIQUE (profile, param_key)
);
CREATE INDEX ix_regulation_param_profile ON regulation_param (profile);

-- ---------------------------------------------------------------------------
-- 21. legal_dong_code — 법정동코드 참조 테이블 (행정안전부 공개 데이터)
