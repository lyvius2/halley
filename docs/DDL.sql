-- =============================================================================
-- Halley — 부동산 매물 비교·평가 웹앱 DB 스키마 (PostgreSQL)
--
-- 대상 : live = PostgreSQL, local = H2 (PostgreSQL 호환 모드)
--        JSONB 등 PostgreSQL 전용 기능은 outbound adapter 뒤에 격리한다 (설계서 2.3).
-- 명명 : snake_case, PK는 BIGINT IDENTITY (자연키 테이블 제외).
-- 근거 : docs/DESIGN.md 4장(ERD), 10.2(임장), 3.4/16-I35(규제 파라미터), 5.5(법정동코드)
--
-- 운영 DB가 이 파일의 어느 시점에 멈춰 있어 기동하지 못한다면
-- (`relation "..." does not exist`), 이 파일을 다시 돌리지 말고
-- **docs/DDL-repair.sql** 을 쓴다. 전부 IF NOT EXISTS 라 현재 상태와 무관하게
-- 안전하고, 몇 번을 돌려도 같은 결과다.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. users — 사용자 (Admin이 생성, 회원가입 없음)
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id             VARCHAR(50)  NOT NULL,                        -- 로그인 ID (설계 I51)
    nickname             VARCHAR(50)  NOT NULL,
    email                VARCHAR(255),                                  -- 연락처. 최초 설정에서 강제 입력
    password_hash        VARCHAR(255) NOT NULL,
    role                 VARCHAR(20)  NOT NULL DEFAULT 'MEMBER',        -- ADMIN | MEMBER
    workplace_name       VARCHAR(255),
    workplace_lat        NUMERIC(12, 8),
    workplace_lng        NUMERIC(12, 8),
    must_change_password BOOLEAN      NOT NULL DEFAULT TRUE,
    available_budget     BIGINT       NOT NULL DEFAULT 0,               -- 보유 현금(원) — 예산상한 합산·자기자본 (I55)
    annual_income        BIGINT       NOT NULL DEFAULT 0,               -- 연소득(원) — DSR 산정 (설계 I55)
    existing_loan        BIGINT       NOT NULL DEFAULT 0,               -- 기존 대출 잔액(원) — DSR 차감
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    disabled_at          TIMESTAMPTZ,
    disabled_by          BIGINT       REFERENCES users (id),
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_nickname ON users (nickname);
CREATE UNIQUE INDEX ux_users_email    ON users (email);
CREATE UNIQUE INDEX ux_users_login_id ON users (login_id);
CREATE INDEX        ix_users_role     ON users (role);

-- ---------------------------------------------------------------------------
-- 2. property — 매물
-- ---------------------------------------------------------------------------
CREATE TABLE property (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(255),                                  -- 단지명
    dong_ho               VARCHAR(100),                                  -- 동/호
    deal_type             VARCHAR(20),                                   -- SALE | JEONSE | MONTHLY
    price_deposit         BIGINT,                                        -- 매매가 or 보증금(원)
    maintenance_fee       INTEGER,
    address_road          VARCHAR(500),
    address_jibun         VARCHAR(500),
    lat                   NUMERIC(12, 8),
    lng                   NUMERIC(12, 8),
    area_supply_m2        NUMERIC(10, 2),                                -- 공급면적(㎡)
    area_exclusive_m2     NUMERIC(10, 2),                                -- 전용면적(㎡)
    floor_raw             VARCHAR(50),                                   -- '7' or '고/중/저'
    floor_no              INTEGER,
    floor_total           INTEGER,
    floor_band            VARCHAR(10),                                   -- HIGH | MID | LOW
    room_bath             VARCHAR(20),                                   -- '3/2'
    direction             VARCHAR(50),
    approval_year         INTEGER,                                       -- 사용승인연도
    move_in_type          VARCHAR(20),                                   -- IMMEDIATE | NEGOTIABLE | DATE
    move_in_date          DATE,
    parking_per_household NUMERIC(5, 2),                                 -- 세대당 주차대수
    total_households      INTEGER,
    heating_type          VARCHAR(50),
    building_count        INTEGER,                                       -- 단지 동수 — 수기 입력
    kb_price              BIGINT,                                        -- KB시세 — 대출 산정 기준
    brokerage_fee         BIGINT,                                        -- 중개보수 상한액(원) — 설계 I53
    brokerage_rate        NUMERIC(4, 2),                                 -- 중개보수 상한 요율(%)
    acquisition_tax       BIGINT,                                        -- 취득세 합계(원)
    property_tax          BIGINT,                                        -- 재산세 합계(원)
    comprehensive_tax     VARCHAR(100),                                  -- 종합부동산세 — '과세대상 아님' 등 문구 그대로
    school_name           VARCHAR(255),                                  -- 배정 초등학교
    school_walk_minutes   INTEGER,                                       -- 초등학교 도보 분
    school_source         VARCHAR(20),                                   -- PASTE | KAKAO (파싱 실패 시 비동기 보정)
    pnu                   VARCHAR(19),                                   -- 필지고유번호 — 공시가격 조회 키 (설계 I54)
    official_price        BIGINT,                                        -- 공시가격(원)
    official_price_year   INTEGER,                                       -- 공시가격 기준연도
    source_type           VARCHAR(20),                                   -- MANUAL | PASTE | CRAWL
    source_url            VARCHAR(1000),                                 -- 원본(네이버) URL — 생존 확인 배치 대상 (설계 I62)
    naver_article_no      VARCHAR(50),                                   -- 매물번호
    raw_paste_text        TEXT,                                          -- 원문 보존 → 재파싱용
    parser_version        VARCHAR(50),
    parse_confidence      JSONB,                                         -- 필드별 EXACT|DERIVED|MISSING
    is_draft              BOOLEAN      NOT NULL DEFAULT FALSE,
    listing_status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',        -- ACTIVE|SOLD_OUT|UNREACHABLE|ARCHIVED
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    last_checked_at       TIMESTAMPTZ,
    check_fail_streak     INTEGER      NOT NULL DEFAULT 0,
    sold_detected_at      TIMESTAMPTZ,
    created_by            BIGINT       REFERENCES users (id),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_property_listing_status ON property (listing_status, active);
CREATE INDEX ix_property_deal_type      ON property (deal_type);
CREATE INDEX ix_property_created_by     ON property (created_by);
CREATE INDEX ix_property_name           ON property (name);
CREATE INDEX ix_property_source_url     ON property (source_url) WHERE source_url IS NOT NULL;

