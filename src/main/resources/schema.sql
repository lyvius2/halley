    area_exclusive_m2     DECIMAL(10, 2),
    floor_raw             VARCHAR(50),
    floor_no              INTEGER,
    floor_total           INTEGER,
    floor_band            VARCHAR(10),
    room_bath             VARCHAR(20),
    direction             VARCHAR(50),
    approval_year         INTEGER,
    move_in_type          VARCHAR(20),
    move_in_date          DATE,
    parking_per_household DECIMAL(5, 2),
    total_households      INTEGER,
    heating_type          VARCHAR(50),
    building_count        INTEGER,
    kb_price              BIGINT,
    brokerage_fee         BIGINT,
    brokerage_rate        NUMERIC(4, 2),
    acquisition_tax       BIGINT,
    property_tax          BIGINT,
