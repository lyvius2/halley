-- Halley — H2(local) 스키마 (jOOQ 영속화용)
-- live(PostgreSQL) 스키마는 docs/DDL.sql 참조. JSONB → JSON, TEXT → VARCHAR로 치환.

CREATE TABLE IF NOT EXISTS users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id             VARCHAR(50)   NOT NULL,
    nickname             VARCHAR(50)   NOT NULL,
    email                VARCHAR(255),
    password_hash        VARCHAR(255)  NOT NULL,
    role                 VARCHAR(20)   NOT NULL DEFAULT 'MEMBER',
    workplace_name       VARCHAR(255),
    workplace_lat        DECIMAL(12, 8),
    workplace_lng        DECIMAL(12, 8),
    must_change_password BOOLEAN       NOT NULL DEFAULT TRUE,
    available_budget     BIGINT        NOT NULL DEFAULT 0,
    annual_income        BIGINT       NOT NULL DEFAULT 0,
    existing_loan        BIGINT       NOT NULL DEFAULT 0,
    enabled              BOOLEAN       NOT NULL DEFAULT TRUE,
    disabled_at          TIMESTAMP WITH TIME ZONE,
    disabled_by          BIGINT,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_nickname ON users (nickname);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email    ON users (email);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_login_id ON users (login_id);

