-- 단지 (설계 I266). 매물이 여기에 딸린다 — 단지 1 : 매물 N.
-- 그룹으로 가르지 않는다. 아파트 단지는 공개 정보이고, 격리는 property.group_id 가 한다
CREATE TABLE IF NOT EXISTS complex (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_key     VARCHAR(300) NOT NULL UNIQUE,
    name          VARCHAR(200) NOT NULL,
    address_jibun VARCHAR(300),
    lat           NUMERIC(10, 7),
    lng           NUMERIC(10, 7),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 국토부 실거래는 매물이 아니라 <단지 + 평형>에 붙는다 (설계 I266).
-- 같은 단지 같은 평형이면 매물이 몇이든 국토부를 한 번만 부른다
CREATE TABLE IF NOT EXISTS reference_transaction (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complex_id    BIGINT NOT NULL,
    deal_type     VARCHAR(20),
    contract_date DATE,
    price         BIGINT,
    area_m2       NUMERIC(10, 2),
    floor_no      INTEGER,
    source        VARCHAR(30),
    cached_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_reference_transaction_complex
    ON reference_transaction (complex_id, area_m2);

