    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id    BIGINT       NOT NULL,
    direction      VARCHAR(20)  NOT NULL,
    -- LLM 이 스스로 낸 결론 (설계 I249). direction 은 규칙까지 거친 최종 결론이라
    -- 둘이 다를 수 있다 — 누가 무엇을 말했는지 남겨야 '유력'을 가릴 수 있다
    llm_direction  VARCHAR(20),
    code_direction VARCHAR(20),
    confidence     VARCHAR(20)  NOT NULL,
    horizon_months INT          NOT NULL,
    factors        JSON,
    caveats        JSON,
    model          VARCHAR(100),
    prompt_hash    VARCHAR(64),
    computed_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_price_forecast_history_property
    ON price_forecast_history (property_id, computed_at DESC);
